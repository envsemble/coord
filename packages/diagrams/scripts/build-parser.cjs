// Generates lib/plantuml/parser.cjs from the grammar. The parser is committed
// like the rest of lib/; `--check` fails when it is not the grammar's.
const fs = require("node:fs");
const path = require("node:path");
const peggy = require("peggy");
const directory = path.resolve(__dirname, "../lib/plantuml");
const grammarFile = path.join(directory, "plantuml.peggy");
const parserFile = path.join(directory, "parser.cjs");
function generateParser() {
  const grammar = fs.readFileSync(grammarFile, "utf8").replace(/\r\n/g, "\n");
  const source = peggy.generate(grammar, {
    output: "source",
    format: "commonjs",
    grammarSource: "plantuml.peggy",
  });
  return `// Generated by scripts/build-parser.cjs from plantuml.peggy with Peggy ${peggy.VERSION}. Do not edit.\n// The grammar derives from plantuml-parser (Apache-2.0, licenses/plantuml-parser-LICENSE).\n${source.replace(/\r\n/g, "\n")}`;
}
const parserIsCurrent = () =>
  fs.existsSync(parserFile) &&
  fs.readFileSync(parserFile, "utf8").replace(/\r\n/g, "\n") ===
    generateParser();
module.exports = { generateParser, parserIsCurrent };
if (require.main === module) {
  if (process.argv.includes("--check")) {
    if (!parserIsCurrent()) {
      console.error(
        "lib/plantuml/parser.cjs is stale: run node scripts/build-parser.cjs",
      );
      process.exitCode = 1;
    }
  } else fs.writeFileSync(parserFile, generateParser());
}
