// Provenance taxonomy shared with Atlas's viewer (`describeProvenance` there): identical labels and
// detail lines, worked out here from a diagram file's description.
export type ProvenanceKind = 'generated' | 'proposal' | 'authored' | 'unknown';
export type ProvenanceTone = 'accent' | 'done' | 'success' | 'neutral';
export interface Provenance { kind: ProvenanceKind; label: string; detail: string; tone: ProvenanceTone }
/** A capture's header, as far as provenance reads it. */
export interface CaptureSource { capturedAt?: string; source?: { kind?: string; identity?: string }; coverage?: { status?: string } }
/** What a diagram's provenance depends on: its role and profile, and its own capture or, for a proposal, the capture it starts from. */
export interface ProvenanceSource { role: string; profile: string | null; capture?: CaptureSource | null }

const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const sourceKinds: Record<string, string> = {
  typescript: 'TypeScript', javascript: 'JavaScript', java: 'Java', sqlite: 'SQLite', postgres: 'PostgreSQL',
  postgresql: 'PostgreSQL', d1: 'Cloudflare D1', mysql: 'MySQL',
};
const authored: Record<string, string> = { class: 'Class diagram', object: 'Object diagram', database: 'Entity diagram', code: 'Class diagram' };

/** "Mon D, YYYY" in UTC, so the server and browser render the same capture date. */
export function captureDate(value: string | undefined): string {
  const time = value ? Date.parse(value) : NaN;
  if (!Number.isFinite(time)) return '';
  const date = new Date(time);
  return `${months[date.getUTCMonth()]} ${date.getUTCDate()}, ${date.getUTCFullYear()}`;
}
function sourceKind(kind: string | undefined) {
  if (!kind) return '';
  return sourceKinds[kind.toLowerCase()] ?? kind.charAt(0).toUpperCase() + kind.slice(1);
}

/** Where a diagram comes from: generated by a capture, proposed over one, or authored. */
export function describeProvenance(diagram: ProvenanceSource | null | undefined): Provenance {
  if (!diagram) return { kind: 'unknown', label: '', detail: '', tone: 'neutral' };
  const capture = diagram.capture;
  const captured = captureDate(capture?.capturedAt);
  if (diagram.role === 'capture') {
    const label = diagram.profile === 'database' ? 'Generated from database' : 'Generated from code';
    const coverage = capture?.coverage?.status;
    const detail = [sourceKind(capture?.source?.kind), capture?.source?.identity, captured && 'captured ' + captured, coverage && coverage + ' coverage'].filter(Boolean).join(' · ');
    return { kind: 'generated', label, detail, tone: 'accent' };
  }
  if (diagram.role === 'proposal') return { kind: 'proposal', label: 'Agent proposal', detail: captured ? 'Changes to source captured ' + captured : '', tone: 'done' };
  return { kind: 'authored', label: 'Agent-authored', detail: authored[diagram.profile ?? ''] ?? 'Diagram', tone: 'success' };
}

/** What the diagram picker needs to describe a diagram in one line. */
export interface ModelSummarySource {
  profile: string | null;
  provenance: { kind: string; detail: string };
}

const subjects: Record<string, string> = { code: 'the code', database: 'the database' };

/**
 * One short line under a diagram's title in the picker: where a capture came from and when
 * ("TypeScript · captured Sep 14, 2026"), what a proposal changes ("Changes to the code captured
 * Sep 14, 2026", or with its count of changes, once known, "15 changes to the code captured Sep 14,
 * 2026"), or what an authored diagram is ("Class diagram").
 */
export function modelSummary(model: ModelSummarySource, changes?: number | null): string {
  const parts = model.provenance.detail.split(' · ').filter(Boolean);
  let line: string;
  if (model.provenance.kind === 'generated') {
    // The detail reads "<source kind> · <identity> · captured <date> · <coverage> coverage".
    const captured = parts.findIndex(part => part.startsWith('captured '));
    line = captured >= 0 ? [...(captured > 0 ? [parts[0]] : []), parts[captured]].join(' · ') : parts.filter(part => !part.endsWith(' coverage')).join(' · ');
  } else if (model.provenance.kind === 'proposal') {
    const date = /captured (.+)$/.exec(model.provenance.detail)?.[1];
    const subject = subjects[model.profile ?? ''] ?? 'the diagram';
    const what = changes == null ? 'Changes' : changes === 0 ? 'No changes' : changes === 1 ? '1 change' : changes + ' changes';
    line = date ? `${what} to ${subject} captured ${date}` : `${what} to ${subject}`;
  } else line = parts.join(' · ');
  return line.charAt(0).toUpperCase() + line.slice(1);
}

/** What naming an element needs of a diagram's model. */
export interface ElementSource { classes: { id: string; name: string }[] }

/**
 * The element a link's fragment names: an id (a class's PlantUML name or alias, a member or a
 * relation) as it is, otherwise the class with that display name, so `#Order%20Item` reaches
 * `class "Order Item" as OrderItem`.
 */
export function elementId(model: ElementSource, element: string): string {
  if (model.classes.some(item => item.id === element)) return element;
  return model.classes.find(item => item.name === element)?.id ?? element;
}
